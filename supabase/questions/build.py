"""Builds supabase/migrations/0006_more_practice_questions.sql from the *.txt files here.

Each file has blocks like:

    ## a1-to-be 2
    question | correct answer | wrong answer | wrong answer

Every block adds 13 questions (positions 3-15) to one practice part of a lesson,
so with the 2 existing ones each part ends up with 15. Options are shuffled with a
fixed seed so the correct answer is not always first.

Run: python3 supabase/questions/build.py
"""

import hashlib
import pathlib
import random

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / "migrations" / "0006_more_practice_questions.sql"
PER_PART = 13
FIRST_POSITION = 3


def sql(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def parse(path: pathlib.Path):
    rows, slug, part = [], None, None
    for n, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        if line.startswith("## "):
            slug, part = line[3:].split()
            part = int(part)
            assert part in (2, 4), f"{path.name}:{n} part must be 2 or 4"
            continue
        fields = [f.strip() for f in line.split(" | ")]
        assert len(fields) == 4, f"{path.name}:{n} needs question | correct | wrong | wrong"
        assert len(set(fields[1:])) == 3, f"{path.name}:{n} options must differ"
        rows.append((slug, part, fields[0], fields[1:]))
    return rows


def main():
    rows = []
    for f in sorted(HERE.glob("*.txt")):
        rows += parse(f)

    counts = {}
    for slug, part, *_ in rows:
        counts[(slug, part)] = counts.get((slug, part), 0) + 1
    bad = {k: v for k, v in counts.items() if v != PER_PART}
    assert not bad, f"each part needs {PER_PART} questions: {bad}"
    assert len({s for s, _ in counts}) == 60, "expected 60 lessons"

    values, position = [], {}
    for slug, part, question, (right, *wrong) in rows:
        key = (slug, part)
        pos = position.get(key, FIRST_POSITION)
        position[key] = pos + 1
        options = [right, *wrong]
        seed = int(hashlib.sha1(f"{slug}{part}{question}".encode()).hexdigest(), 16)
        random.Random(seed).shuffle(options)
        arr = "array[" + ", ".join(sql(o) for o in options) + "]"
        values.append(f"({sql(slug)}, {part}, {pos}, {sql(question)}, {arr}, {options.index(right)})")

    OUT.write_text(
        "-- 13 more practice questions for each practice part of every lesson,\n"
        "-- so each part (2 and 4) has 15 questions: 1560 new questions in total.\n"
        "-- Generated by supabase/questions/build.py. Safe to run twice.\n\n"
        "insert into lesson_questions (lesson_id, part, position, question, options, correct)\n"
        "select l.id, v.part, v.position, v.question, v.options, v.correct\n"
        "from (values\n" + ",\n".join(values) + "\n"
        ") as v(slug, part, position, question, options, correct)\n"
        "join lessons l on l.slug = v.slug\n"
        "where not exists (\n"
        "  select 1 from lesson_questions x\n"
        "  where x.lesson_id = l.id and x.part = v.part and x.position = v.position\n"
        ");\n"
    )
    print(f"wrote {len(values)} questions to {OUT}")


if __name__ == "__main__":
    main()
