"""Builds supabase/migrations/0009_lesson_vocab.sql and 0014_vocab_example_translations.sql
from the *.txt files here.

Each file has blocks like:

    ## a1-to-be
    w | teacher | müəllim | учитель | My [teacher] is very kind. | Mənim müəllimim çox mehribandır. | Мой учитель очень добрый.
    p | come in | içəri gəlmək | входить | Please [come in] and sit down. | Zəhmət olmasa, içəri gəlin və oturun. | Пожалуйста, входите и садитесь.

Every lesson has 20 words (w) and 5 phrasal verbs (p). The part of the example in
[brackets] is the gap in the vocabulary test. The last two fields translate the example
into Azerbaijani and Russian.

Run: python3 supabase/vocab/build.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / "migrations" / "0009_lesson_vocab.sql"
OUT_EXAMPLES = HERE.parent / "migrations" / "0014_vocab_example_translations.sql"
WORDS, PHRASALS = 20, 5
GAP = re.compile(r"^[^\[\]]*\[[^\[\]]+\][^\[\]]*$")


def sql(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def parse(path: pathlib.Path):
    rows, slug = [], None
    for n, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        if line.startswith("## "):
            slug = line[3:].strip()
            continue
        fields = [f.strip() for f in line.split(" | ")]
        assert len(fields) == 7, f"{path.name}:{n} needs kind | term | az | ru | example | example az | example ru"
        assert fields[0] in ("w", "p"), f"{path.name}:{n} kind must be w or p"
        assert all(fields), f"{path.name}:{n} empty field"
        assert GAP.match(fields[4]), f"{path.name}:{n} example needs exactly one [gap]"
        rows.append((slug, *fields))
    return rows


def main():
    rows = []
    for f in sorted(HERE.glob("*.txt")):
        rows += parse(f)

    lessons = {}
    for slug, kind, term, az, ru, example, _, _ in rows:
        lessons.setdefault(slug, {"w": [], "p": [], "az": [], "ru": [], "gap": []})[kind].append(term.lower())
        lessons[slug]["az"].append(az.lower())
        lessons[slug]["ru"].append(ru.lower())
        lessons[slug]["gap"].append(example.split("[")[1].split("]")[0].lower())
    problems = []
    for slug, k in lessons.items():
        if len(k["w"]) != WORDS or len(k["p"]) != PHRASALS:
            problems.append(f"{slug}: {len(k['w'])} words, {len(k['p'])} phrasal verbs")
        k["term"] = k["w"] + k["p"]
        for col in ("term", "az", "ru", "gap"):
            dup = {x for x in k[col] if k[col].count(x) > 1}
            if dup:
                problems.append(f"{slug}: duplicate {col} {dup}")
    assert not problems, "\n".join(problems)
    assert len(lessons) == 66, f"expected 66 lessons, got {len(lessons)}"

    values, examples, position = [], [], {}
    # Words first, then phrasal verbs, in file order.
    for kind in ("w", "p"):
        for slug, k, term, az, ru, example, example_az, example_ru in rows:
            if k != kind:
                continue
            pos = position.get(slug, 1)
            position[slug] = pos + 1
            word = "word" if kind == "w" else "phrasal"
            values.append(f"({sql(slug)}, {pos}, '{word}', {sql(term)}, {sql(az)}, {sql(ru)}, {sql(example)})")
            examples.append(f"({sql(slug)}, {pos}, {sql(example_az)}, {sql(example_ru)})")

    OUT.write_text(
        "-- Vocabulary for every lesson: 20 words and 5 phrasal verbs with Azerbaijani and\n"
        "-- Russian translations and an example sentence. The [bracketed] part of the example\n"
        "-- is the gap in the vocabulary test. Readable after the lesson is bought.\n"
        "-- Generated by supabase/vocab/build.py. Safe to run twice.\n\n"
        "create table if not exists lesson_vocab (\n"
        "  id serial primary key,\n"
        "  lesson_id int not null references lessons on delete cascade,\n"
        "  position int not null,\n"
        "  kind text not null check (kind in ('word', 'phrasal')),\n"
        "  term text not null,\n"
        "  az text not null,\n"
        "  ru text not null,\n"
        "  example text not null,\n"
        "  unique (lesson_id, position)\n"
        ");\n\n"
        "alter table lesson_vocab enable row level security;\n\n"
        "drop policy if exists \"vocab after purchase\" on lesson_vocab;\n"
        "create policy \"vocab after purchase\" on lesson_vocab for select using (\n"
        "  exists (select 1 from lesson_purchases p where p.lesson_id = lesson_vocab.lesson_id and p.student_id = auth.uid())\n"
        ");\n\n"
        "insert into lesson_vocab (lesson_id, position, kind, term, az, ru, example)\n"
        "select l.id, v.position, v.kind, v.term, v.az, v.ru, v.example\n"
        "from (values\n" + ",\n".join(values) + "\n"
        ") as v(slug, position, kind, term, az, ru, example)\n"
        "join lessons l on l.slug = v.slug\n"
        "where not exists (\n"
        "  select 1 from lesson_vocab x where x.lesson_id = l.id and x.position = v.position\n"
        ");\n\n"
        "notify pgrst, 'reload schema';\n"
    )
    OUT_EXAMPLES.write_text(
        "-- Azerbaijani and Russian translations of the vocabulary example sentences,\n"
        "-- shown under each example in the lesson's Vocabulary step.\n"
        "-- Run after 0009_lesson_vocab.sql and 0013_c2_content.sql.\n"
        "-- Generated by supabase/vocab/build.py. Safe to run twice.\n\n"
        "alter table lesson_vocab add column if not exists example_az text not null default '';\n"
        "alter table lesson_vocab add column if not exists example_ru text not null default '';\n\n"
        "update lesson_vocab x set example_az = v.example_az, example_ru = v.example_ru\n"
        "from (values\n" + ",\n".join(examples) + "\n"
        ") as v(slug, position, example_az, example_ru)\n"
        "join lessons l on l.slug = v.slug\n"
        "where x.lesson_id = l.id and x.position = v.position;\n\n"
        "notify pgrst, 'reload schema';\n"
    )
    print(f"wrote {len(values)} entries for {len(lessons)} lessons to {OUT} and {OUT_EXAMPLES}")


if __name__ == "__main__":
    main()
